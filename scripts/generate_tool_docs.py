"""Regenerates docs/tools.md from the live tool registry.

    python scripts/generate_tool_docs.py          # write docs/tools.md
    python scripts/generate_tool_docs.py --check  # fail if docs/tools.md is stale (used by CI)
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "Content", "Python"))
os.environ.setdefault("CONAN_MCP_QUIET", "1")

from conan_mcp.core import config  # noqa: E402
from conan_mcp.core.registry import prompt_registry, registry, resource_registry  # noqa: E402
from conan_mcp.server import register_everything  # noqa: E402

ORDER = ["System", "Mapping", "Landscape", "Capture", "Level", "Actors", "Editor", "Assets", "DataTables",
         "Blueprints", "Animation", "Mod", "Skeletons", "Particles", "Conan", "Scripting"]


def _arg_line(name, spec, required):
    t = spec.get("type", "any")
    if isinstance(t, list):
        t = "/".join(t)
    if "enum" in spec:
        t += " (" + ", ".join(str(e) for e in spec["enum"] if e != "") + ")"
    desc = spec.get("description", "")
    return f"| `{name}`{' *' if name in required else ''} | {t} | {desc} |"


def render() -> str:
    register_everything()
    tools = list(registry.tools.values())
    cats = sorted({t["category"] for t in tools}, key=lambda c: (ORDER.index(c) if c in ORDER else 99, c))
    out = [
        "# ConanMCP tool catalog",
        "",
        f"> Generated by `scripts/generate_tool_docs.py` for ConanMCP {config.SERVER_VERSION}. Do not edit by hand.",
        "",
        f"**{len(tools)} tools**, {len(resource_registry.resources) + len(resource_registry.templates)} resources, "
        f"{len(prompt_registry.prompts)} prompts. `*` marks required arguments.",
        "",
        "Security levels: `READ_ONLY` (always on), `SAFE_WRITE` (undoable edits, off with `CONAN_MCP_READONLY=1`), "
        "`DESTRUCTIVE` (off unless `CONAN_MCP_ENABLE_DESTRUCTIVE=1`).",
        "",
        "## Index",
        "",
    ]
    for c in cats:
        names = sorted(t["name"] for t in tools if t["category"] == c)
        out.append(f"- **{c}**: " + ", ".join(f"[`{n}`](#{n})" for n in names))
    for c in cats:
        out += ["", f"## {c}", ""]
        for t in sorted((t for t in tools if t["category"] == c), key=lambda t: t["name"]):
            out += [f"### `{t['name']}`", "", f"`{t['security']}` · {t['summary']}", ""]
            props = t["inputSchema"].get("properties", {})
            req = t["inputSchema"].get("required", [])
            if props:
                out += ["| Argument | Type | Description |", "|---|---|---|"]
                out += [_arg_line(n, s, req) for n, s in props.items()]
                out.append("")
    out += ["", "## Prompts (skills)", ""]
    out += [f"- `{p['name']}`: {p['description']}" for p in prompt_registry.prompts.values()]
    out += ["", "## Resources", ""]
    out += [f"- `{r['uri']}`: {r['description']}" for r in resource_registry.resources.values()]
    out += [f"- `{t['uriTemplate']}`: {t['description']}" for t in resource_registry.templates]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    path = os.path.join(ROOT, "docs", "tools.md")
    text = render()
    if "--check" in sys.argv:
        with open(path, encoding="utf-8") as f:
            if f.read() != text:
                sys.exit("docs/tools.md is out of date: run python scripts/generate_tool_docs.py")
        print("docs/tools.md is up to date")
    else:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"Wrote {path}")
